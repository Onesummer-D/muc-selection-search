def normalize(text: str) -> str:
    """全角字母数字转半角；只做空格与换行收紧，不改动汉字。"""
    out = text.translate(_FULLWIDTH)
    return out


def context_of(text: str, start: int, end: int, span: int = 20) -> str:
    """取匹配片段及其前后文，作为字段证据文本。"""
    lo, hi = max(0, start - span), min(len(text), end + span)
    snippet = text[lo:hi].replace("\n", " ").strip()
    return snippet if snippet else text[start:end]
